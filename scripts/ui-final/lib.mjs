import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(__dirname, "../..");
export const DB_PATH = path.join(ROOT, "docs/icons/ui-final/UI_FINAL_DB.json");
export const MIRROR_PATH = path.join(ROOT, "game/public/icons/ui-final/UI_FINAL_DB.json");
export const PENDING_DIR = path.join(ROOT, "docs/icons/ui-final/pending");
export const RELEASED_DIR = path.join(ROOT, "game/public/icons/ui-final");
export const TS_PATH = path.join(ROOT, "game/src/game/uiFinal.ts");
export const VALIDATE_PY = path.join(ROOT, "scripts/ui-final/validate.py");

export function readDb() {
  return JSON.parse(fs.readFileSync(DB_PATH, "utf8"));
}

export function writeDb(db) {
  fs.writeFileSync(DB_PATH, JSON.stringify(db, null, 2) + "\n");
}

export function validatePng(filePath) {
  const r = spawnSync("python3", [VALIDATE_PY, filePath, "--json"], {
    encoding: "utf8",
  });
  if (r.status !== 0 && !r.stdout) {
    throw new Error(r.stderr || `validate failed for ${filePath}`);
  }
  return JSON.parse(r.stdout);
}

/** Regenerate runtime mirror JSON + TypeScript resolver from source DB. */
export function syncMirror(db = readDb()) {
  fs.mkdirSync(RELEASED_DIR, { recursive: true });
  const mirror = {
    ...db,
    description:
      db.description +
      " (Runtime-Spiegel — nur released Dateien liegen neben dieser Datei.)",
  };
  fs.writeFileSync(MIRROR_PATH, JSON.stringify(mirror, null, 2) + "\n");

  const released = db.released || {};
  const entries = Object.entries(released).sort(([a], [b]) => a.localeCompare(b));
  const lines = [];
  lines.push("/**");
  lines.push(" * GENERATED by scripts/ui-final/sync.mjs — do not edit by hand.");
  lines.push(" * Source of truth: docs/icons/ui-final/UI_FINAL_DB.json");
  lines.push(" * Only `released` icons are listed. Draw with uniform scale (no distort).");
  lines.push(" */");
  lines.push("");
  lines.push("export type UiFinalId =");
  if (entries.length === 0) {
    lines.push("  | never;");
  } else {
    for (const [id] of entries) {
      lines.push(`  | ${JSON.stringify(id)}`);
    }
    lines.push(";");
  }
  lines.push("");
  lines.push("export type LiveTintMeta = {");
  lines.push("  enabled: true;");
  lines.push('  basePalette: "blue" | "red";');
  lines.push('  pullsFrom: "sideKitPrimary";');
  lines.push('  side: "heim" | "gast";');
  lines.push("};");
  lines.push("");
  lines.push("export type UiFinalEntry = {");
  lines.push("  file: string;");
  lines.push("  path: string;");
  lines.push("  native: { w: number; h: number };");
  lines.push("  aspectRatio: number;");
  lines.push("  preserveAspect: true;");
  lines.push("  freigestellt: boolean;");
  lines.push("  liveTint?: LiveTintMeta;");
  lines.push("};");
  lines.push("");
  lines.push("/** Runtime paths under game/public — only user-approved releases. */");
  lines.push("export const UI_FINAL_PATHS = {");
  for (const [id, e] of entries) {
    const native = e.validation?.native ?? e.native ?? { w: 0, h: 0 };
    const ar = e.validation?.aspectRatio ?? e.aspectRatio ?? 1;
    const freigestellt = e.validation?.freigestellt ?? true;
    const lt = e.liveTint;
    lines.push(`  ${JSON.stringify(id)}: {`);
    lines.push(`    file: ${JSON.stringify(e.file)},`);
    lines.push(`    path: ${JSON.stringify("icons/ui-final/" + e.file)},`);
    lines.push(`    native: { w: ${native.w}, h: ${native.h} },`);
    lines.push(`    aspectRatio: ${ar},`);
    lines.push(`    preserveAspect: true,`);
    lines.push(`    freigestellt: ${freigestellt ? "true" : "false"},`);
    if (lt?.enabled && (lt.basePalette === "blue" || lt.basePalette === "red")) {
      lines.push(`    liveTint: {`);
      lines.push(`      enabled: true,`);
      lines.push(`      basePalette: ${JSON.stringify(lt.basePalette)},`);
      lines.push(`      pullsFrom: "sideKitPrimary",`);
      lines.push(`      side: ${JSON.stringify(lt.side === "gast" ? "gast" : "heim")},`);
      lines.push(`    },`);
    }
    lines.push(`  },`);
  }
  lines.push("} as const satisfies Record<string, UiFinalEntry>;");
  lines.push("");
  lines.push("export function uiFinalIconPath(id: string): string | undefined {");
  lines.push("  const hit = (UI_FINAL_PATHS as Record<string, UiFinalEntry>)[id];");
  lines.push("  return hit?.path;");
  lines.push("}");
  lines.push("");
  lines.push("export function uiFinalNative(id: string): { w: number; h: number } | undefined {");
  lines.push("  const hit = (UI_FINAL_PATHS as Record<string, UiFinalEntry>)[id];");
  lines.push("  return hit?.native;");
  lines.push("}");
  lines.push("");
  lines.push("export function isUiFinalReleased(id: string): boolean {");
  lines.push("  return id in UI_FINAL_PATHS;");
  lines.push("}");
  lines.push("");

  fs.writeFileSync(TS_PATH, lines.join("\n"));
  return { releasedCount: entries.length, tsPath: TS_PATH, mirrorPath: MIRROR_PATH };
}
